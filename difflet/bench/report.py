"""Markdown generated from result JSON, replacing hand-written RESULTS.md files (design §11).

``difflet bench report`` writes ``<results>/<device>/SUMMARY.md`` (one row per recipe: the latest
valid result, with how many older results and hosts exist) and ``REPORT.md`` in every recipe dir
(every result, newest first). The main table holds plain recipes only; suite variants
(``recipe@suite.variant``) and runs with ``--`` overrides (``recipe+fingerprint``) get sections of
their own, showing what differs. No column is specific to an engine feature: a run's settings are
rendered as the flags that differ from its recipe.
"""

from __future__ import annotations

from pathlib import Path
from typing import Any

from difflet.bench import results

COLUMNS = (("compile", "compile", 1.0, "s"), ("e2e_cold", "e2e cold", 1.0, "s"),
           ("e2e_warm", "e2e warm", 1.0, "s"), ("dit_step", "DiT step", 1e3, "ms"),
           ("memory", "peak HBM/rank", 1.0, "GiB"))


def _median(metric: dict[str, Any] | None, scale: float) -> str:
    if not metric:
        return ""
    if metric.get("not_applicable"):
        return "n/a"
    summary = metric.get("summary") or {}
    if not summary.get("n"):
        return "invalid" if not metric.get("valid") else ""
    text = f"{summary['median'] * scale:.4g} (n={summary['n']})"
    return text if metric.get("valid") else f"{text} INVALID"


def _quality(metric: dict[str, Any] | None) -> str:
    if not metric:
        return ""
    comparison = metric.get("comparison") or {}
    frames = comparison.get("frames") or {}
    if not frames:
        return "dump only" if metric.get("valid") or metric.get("not_applicable") else "invalid"
    ref = (metric.get("reference") or {}).get("kind", "?")
    return (f"PSNR min {results.fmt(frames.get('psnr_min'), '.2f')} dB, SSIM min "
            f"{results.fmt(frames.get('ssim_min'), '.4f')} vs {ref}")


def _row(record: dict[str, Any], older: int = 0, hosts: int = 1) -> list[str]:
    metrics = record.get("metrics") or {}
    git = (record.get("provenance") or {}).get("git") or {}
    cells = [record["recipe"]["name"].split("@")[0]]
    cells += [_median(metrics.get(key), scale) for key, _, scale, _ in COLUMNS]
    cells.append(_quality(metrics.get("quality")))
    cells.append("yes" if record.get("valid") else "no")
    cells.append(f"{(git.get('commit') or '?')[:10]}{'+dirty' if git.get('dirty') else ''}")
    cells.append(record["run_id"] + (f" (+{older} older, {hosts} host(s))" if older else ""))
    return cells


def _table(rows: list[list[str]]) -> list[str]:
    header = ["recipe", *[f"{label} ({unit})" for _, label, _, unit in COLUMNS], "quality",
              "valid", "commit", "run"]
    out = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    out += ["| " + " | ".join(r) + " |" for r in rows]
    return out


def _load_device(device_dir: Path) -> dict[str, list[dict[str, Any]]]:
    by_dir: dict[str, list[dict[str, Any]]] = {}
    for path in results.iter_results(device_dir):
        try:
            record = results.read_json(path)
        except ValueError:
            continue
        if record.get("kind") != "result":
            continue
        record["_path"] = str(path)
        by_dir.setdefault(path.parent.name, []).append(record)
    for records in by_dir.values():
        records.sort(key=lambda r: r["run_id"], reverse=True)
    return by_dir


def _overrides(record: dict[str, Any]) -> str:
    recipe = record.get("recipe") or {}
    parts = []
    if recipe.get("variant"):
        parts.append(f"{recipe.get('suite')}.{recipe['variant']}: {recipe.get('variant_args')}")
    if recipe.get("passthrough"):
        parts.append("-- " + " ".join(recipe["passthrough"]))
    return "; ".join(parts)


def render_device(device: str, by_dir: dict[str, list[dict[str, Any]]], *,
                  show_all: bool = False) -> str:
    lines = [f"# difflet bench results: {device}", "",
             "Generated by `difflet bench report` from the result JSON next to this file. Each row "
             "is the latest valid result of a recipe; numbers are medians over the recorded "
             "samples. Do not edit by hand.", ""]
    plain = {k: v for k, v in by_dir.items() if "@" not in k and "+" not in k}
    other = {k: v for k, v in by_dir.items() if k not in plain}
    rows, no_valid = [], []
    for name in sorted(plain):
        records = plain[name]
        valid = [r for r in records if r.get("valid")]
        if show_all:
            rows += [_row(r) for r in records]
        elif valid:
            hosts = len({(r.get("provenance") or {}).get("host_id") for r in records})
            rows.append(_row(valid[0], older=len(records) - 1, hosts=hosts))
        else:
            no_valid.append(f"- {name}: {len(records)} result(s), none valid; latest "
                            f"{records[0]['run_id']}: {records[0].get('aborted') or 'invalid'}")
    lines += ["## Recipes", ""] + (_table(rows) if rows else ["(no valid results)"]) + [""]
    if no_valid:
        lines += ["## Recipes without a valid result", ""] + no_valid + [""]
    if other:
        lines += ["## Suite variants and overridden runs", "",
                  "Not comparable with the table above without reading what differs.", ""]
        rows = []
        for name in sorted(other):
            record = other[name][0]
            rows.append(_row(record) + [_overrides(record)])
        header = _table([])[:2]
        header[0] = header[0][:-1] + " differs from the recipe |"
        header[1] += "---|"
        lines += header + ["| " + " | ".join(r) + " |" for r in rows] + [""]
    return "\n".join(lines)


def render_recipe(name: str, records: list[dict[str, Any]]) -> str:
    lines = [f"# {name}", "", "Every result for this recipe, newest first.", ""]
    for record in records:
        metrics = record.get("metrics") or {}
        lines += [f"## {record['run_id']} ({'valid' if record.get('valid') else 'INVALID'})", "",
                  f"- repro: `{record.get('repro')}`"]
        if record.get("aborted"):
            lines.append(f"- aborted: {record['aborted']}")
        for key, metric in metrics.items():
            reasons = "; ".join(metric.get("invalid_reasons") or [])
            summary = metric.get("summary") or {}
            if summary.get("n"):
                lines.append(f"- {key}: median {summary['median']:.6g} {metric.get('unit', '')}, "
                             f"min {summary['min']:.6g}, max {summary['max']:.6g}, "
                             f"n={summary['n']}" + (f"; INVALID: {reasons}" if reasons else ""))
            elif key == "quality":
                lines.append(f"- quality: {_quality(metric)}"
                             + (f"; INVALID: {reasons}" if reasons else ""))
            else:
                lines.append(f"- {key}: {metric.get('not_applicable') or 'no sample'}"
                             + (f"; INVALID: {reasons}" if reasons else ""))
        breakdown = (metrics.get("e2e_warm") or {}).get("stage_breakdown") or []
        if breakdown:
            lines.append(f"- e2e_warm stage breakdown (first run): {breakdown[0]}")
        lines.append("")
    return "\n".join(lines)


def generate(root: Path, *, show_all: bool = False) -> list[Path]:
    """Write every device's SUMMARY.md and every recipe dir's REPORT.md under ``root``."""
    written = []
    if not root.exists():
        return written
    for device_dir in sorted(p for p in root.iterdir() if p.is_dir()):
        by_dir = _load_device(device_dir)
        if not by_dir:
            continue
        summary = device_dir / "SUMMARY.md"
        summary.write_text(render_device(device_dir.name, by_dir, show_all=show_all) + "\n")
        written.append(summary)
        for name, records in by_dir.items():
            path = device_dir / name / "REPORT.md"
            path.write_text(render_recipe(name, records) + "\n")
            written.append(path)
    return written
