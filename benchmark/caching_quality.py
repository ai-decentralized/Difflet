"""Step-caching output quality for one model: reproducible, resumable, prompt-major.

Every (prompt, config) pair is generated by the exact ``difflet generate`` command the
benchmark cells run (benchmark.adapters.trainium: one process per generation, seed 42,
the model's official steps / guidance / negative prompt / shape from benchmark.models).
Prompts run one after another and, within a prompt, the configs in the order given, so a
stopped run leaves only whole prompts behind. Each caching config is scored against the
caching-off output of the same prompt and seed: PSNR over 8-bit pixels, frame-averaged
for video (benchmark.output_parity.compare), then the mean and the worst prompt per config
-- the protocol of the paper's step-caching evaluation.

    DIFFLET_BENCH_DEVICE=trn2-eval-vc2 python -m benchmark.caching_quality run \\
        --model wan_2_1 --configs tp4 tp4tc2 tp4s30 tp4tcod \\
        --prompts scripts/data/vbench_overall_consistency_first16.txt --git-sync
    DIFFLET_BENCH_DEVICE=trn2-eval-vc2 python -m benchmark.caching_quality score --model wan_2_1

The first config is the reference (caching off). Everything lands in
benchmark/<device>/quality/<model>/:

  manifest.jsonl  a ``run`` record per invocation (arguments, git commit, toolchain, host)
                  and a ``generation`` record per output (command line, wall time, DiT step
                  times, TeaCache stats with the skipped step indices, output sha256)
  progress.json   per-prompt PSNR and the running mean / worst prompt per config
  videos/<config>_p<NN>.mp4 and logs/  (kept out of git; sha256 in the manifest)

``run`` skips pairs whose output already exists, so rerunning the same command resumes.
``--git-sync`` commits manifest.jsonl and progress.json after every finished prompt and
pushes the current branch; a failed push is logged and the run goes on.
"""
from __future__ import annotations

import argparse
import ast
import hashlib
import json
import math
import platform
import re
import statistics
import subprocess
import time
from dataclasses import replace
from pathlib import Path

from benchmark.adapters.trainium import TrainiumAdapter, spec_slug
from benchmark.models import NXD_VENV, resolve, results_dir

REPO = Path(__file__).resolve().parent.parent
_RE_STATS = re.compile(r"\[teacache\] stats: (\{.*\})")
_TOOLCHAIN = ("torch", "torch-neuronx", "neuronx-cc", "neuronx-distributed", "nki")
_MAX_FAILURES = 2  # a config that fails this many times is dropped for the rest of the run


def read_prompts(path: str | Path) -> list[str]:
    lines = Path(path).read_text(encoding="utf-8").splitlines()
    return [ln.strip() for ln in lines if ln.strip() and not ln.lstrip().startswith("#")]


def out_root(model: str) -> Path:
    return REPO / results_dir() / "quality" / model


def video_path(root: Path, config: str, i: int) -> Path:
    return root / "videos" / f"{config}_p{i:02d}.mp4"


def utc() -> str:
    return time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime())


def sha256(path: Path) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as fh:
        for block in iter(lambda: fh.read(1 << 20), b""):
            h.update(block)
    return h.hexdigest()


def git(*args: str) -> subprocess.CompletedProcess:
    return subprocess.run(["git", "-C", str(REPO), *args], capture_output=True, text=True)


def git_state() -> dict:
    dirty = git("status", "--porcelain", "--untracked-files=no").stdout.strip()
    return {"commit": git("rev-parse", "HEAD").stdout.strip(),
            "branch": git("rev-parse", "--abbrev-ref", "HEAD").stdout.strip(),
            "dirty": bool(dirty)}


def toolchain() -> dict:
    code = ("import importlib.metadata as m, json\n"
            "out = {}\n"
            f"for p in {_TOOLCHAIN!r}:\n"
            "    try: out[p] = m.version(p)\n"
            "    except m.PackageNotFoundError: out[p] = None\n"
            "print(json.dumps(out))")
    res = subprocess.run([f"{NXD_VENV}/bin/python", "-c", code], capture_output=True, text=True)
    try:
        return json.loads(res.stdout.strip().splitlines()[-1])
    except (IndexError, json.JSONDecodeError):
        return {"error": res.stderr.strip()[-300:]}


def append(root: Path, record: dict) -> None:
    with open(root / "manifest.jsonl", "a", encoding="utf-8") as fh:
        fh.write(json.dumps(record, ensure_ascii=False) + "\n")


def load_manifest(root: Path) -> list[dict]:
    path = root / "manifest.jsonl"
    if not path.exists():
        return []
    return [json.loads(ln) for ln in path.read_text(encoding="utf-8").splitlines() if ln.strip()]


def teacache_stats(log: Path) -> dict | None:
    """The last ``[teacache] stats: {...}`` line of a generate log, minus the delta trace."""
    hits = _RE_STATS.findall(log.read_text(errors="ignore")) if log.exists() else []
    if not hits:
        return None
    stats = ast.literal_eval(hits[-1])
    stats.pop("delta_trace", None)
    return stats


class RecordingAdapter(TrainiumAdapter):
    """TrainiumAdapter that keeps the last command line for the manifest."""

    last_cmd: list[str] = []

    def _run(self, cmd, log, timeout):
        self.last_cmd = list(cmd)
        return super()._run(cmd, log, timeout)


def score(root: Path, model: str, prompts: list[str], configs: list[str]) -> dict:
    """Rescore every finished pair from disk and write progress.json."""
    from benchmark.output_parity import compare

    ref, rest = configs[0], configs[1:]
    per_prompt: dict[str, dict] = {c: {} for c in rest}
    for i in range(len(prompts)):
        a = video_path(root, ref, i)
        for c in rest:
            b = video_path(root, c, i)
            if a.exists() and b.exists():
                per_prompt[c][i] = compare(a, b)
    complete = [i for i in range(len(prompts))
                if all(video_path(root, c, i).exists() for c in configs)]
    summary = {}
    for c in rest:
        finite = {i: r["psnr_db"] for i, r in per_prompt[c].items()
                  if i in complete and math.isfinite(r["psnr_db"])}
        identical = [i for i, r in per_prompt[c].items() if i in complete and r.get("identical")]
        summary[c] = {
            "prompts": len(finite),
            "mean_psnr_db": round(statistics.mean(finite.values()), 2) if finite else None,
            "worst_psnr_db": round(min(finite.values()), 2) if finite else None,
            "worst_prompt": min(finite, key=finite.get) if finite else None,
            "identical_to_reference": identical,
        }
    baseline = "tp4s30" if "tp4s30" in rest else None
    beats = None
    if baseline:
        pairs = [(c, i) for c in rest if c != baseline for i in complete
                 if i in per_prompt[c] and i in per_prompt[baseline]]
        wins = sum(per_prompt[c][i]["psnr_db"] > per_prompt[baseline][i]["psnr_db"]
                   for c, i in pairs)
        beats = {"baseline": baseline, "wins": wins, "pairs": len(pairs)}
    progress = {
        "model": model, "reference": ref, "configs": configs, "updated_utc": utc(),
        "complete_prompts": complete, "prompts_total": len(prompts),
        "metric": "PSNR (dB, 8-bit), frame-averaged, vs the reference output of the same "
                  "prompt and seed (benchmark.output_parity.compare); worst = lowest "
                  "prompt mean; identical outputs (infinite PSNR) are excluded from the "
                  "mean and listed",
        "summary": summary,
        "caching_beats_baseline": beats,
        "per_prompt": {c: {str(i): {k: r.get(k) for k in ("psnr_db", "psnr_min_db",
                                                           "mean_abs_diff", "identical")}
                           for i, r in sorted(per_prompt[c].items())} for c in rest},
        "prompts": prompts,
    }
    (root / "progress.json").write_text(json.dumps(progress, indent=2, ensure_ascii=False) + "\n")
    return progress


def git_sync(root: Path, message: str) -> None:
    rel = [str((root / name).relative_to(REPO)) for name in ("manifest.jsonl", "progress.json",
                                                              ".gitignore")]
    steps = (("add", "--", *rel), ("commit", "-m", message, "--", *rel),
             ("push", "origin", "HEAD"))
    for args in steps:
        res = git(*args)
        if res.returncode != 0:
            print(f"[quality] git {args[0]} failed: {res.stderr.strip()[-300:]}", flush=True)
            return
    print(f"[quality] pushed: {message}", flush=True)


def run(args) -> int:
    prompts = read_prompts(args.prompts)
    if args.limit:
        prompts = prompts[:args.limit]
    root = out_root(args.model)
    (root / "videos").mkdir(parents=True, exist_ok=True)
    (root / "logs").mkdir(parents=True, exist_ok=True)
    (root / ".gitignore").write_text("videos/\nlogs/\n*_out.mp4\n")
    run_id = utc()
    append(root, {"type": "run", "run_id": run_id, "model": args.model,
                  "configs": args.configs, "prompts_file": str(Path(args.prompts)),
                  "prompts": prompts, "git": git_state(), "toolchain": toolchain(),
                  "host": platform.node(), "results_dir": results_dir(),
                  "venv": NXD_VENV})
    adapter = RecordingAdapter(log_dir=str(root / "logs"))
    failures: dict[str, int] = {}
    for i, prompt in enumerate(prompts):
        for config in args.configs:
            dst = video_path(root, config, i)
            if dst.exists():
                continue
            if failures.get(config, 0) >= _MAX_FAILURES:
                continue
            cfg = replace(resolve(args.model, config), prompt=prompt)
            produced = root / f"{spec_slug(cfg)}_out.mp4"
            started = utc()
            record = {"type": "generation", "run_id": run_id, "prompt_index": i,
                      "prompt": prompt, "config": config, "started_utc": started}
            try:
                res = adapter.run_generate(cfg)
            except Exception as exc:  # noqa: BLE001 -- recorded and the run goes on
                failures[config] = failures.get(config, 0) + 1
                record.update(status="failed", finished_utc=utc(), error=str(exc)[-2000:],
                              command=adapter.last_cmd)
                append(root, record)
                print(f"[quality] p{i:02d} {config} FAILED: {str(exc)[-300:]}", flush=True)
                continue
            produced.replace(dst)
            steps = res.get("step_seconds") or []
            record.update(
                status="ok", finished_utc=utc(),
                wall_seconds=round(res["wall_seconds"], 1),
                load_seconds=res.get("load_seconds"),
                dit_calls=len(steps),
                dit_step_median_s=round(statistics.median(steps), 3) if steps else None,
                teacache=teacache_stats(Path(res["log"])),
                output=str(dst.relative_to(root)), sha256=sha256(dst),
                command=adapter.last_cmd)
            append(root, record)
            print(f"[quality] p{i:02d} {config} {record['wall_seconds']}s -> {dst.name}",
                  flush=True)
        if all(video_path(root, c, i).exists() for c in args.configs):
            progress = score(root, args.model, prompts, args.configs)
            line = ", ".join(f"{c} {s['mean_psnr_db']} dB" for c, s in progress["summary"].items())
            print(f"[quality] prompt {i:02d} done ({len(progress['complete_prompts'])} complete): "
                  f"{line}", flush=True)
            if args.git_sync:
                git_sync(root, f"data({args.model}): caching quality, "
                               f"{len(progress['complete_prompts'])} of {len(prompts)} prompts")
    return 0


def rescore(args) -> int:
    root = out_root(args.model)
    runs = [r for r in load_manifest(root) if r.get("type") == "run"]
    if not runs:
        print(f"[quality] no manifest under {root}")
        return 1
    last = runs[-1]
    progress = score(root, args.model, last["prompts"], last["configs"])
    print(json.dumps(progress["summary"], indent=2))
    return 0


def main() -> int:
    p = argparse.ArgumentParser()
    sub = p.add_subparsers(dest="cmd", required=True)
    r = sub.add_parser("run")
    r.add_argument("--model", required=True)
    r.add_argument("--configs", nargs="+", required=True,
                   help="first = reference (caching off), e.g. tp4 tp4tc2 tp4s30 tp4tcod")
    r.add_argument("--prompts", required=True, help="one prompt per non-comment line")
    r.add_argument("--limit", type=int, default=0, help="first N prompts only (0 = all)")
    r.add_argument("--git-sync", action="store_true",
                   help="commit manifest/progress after every finished prompt and push")
    s = sub.add_parser("score")
    s.add_argument("--model", required=True)
    a = p.parse_args()
    return run(a) if a.cmd == "run" else rescore(a)


if __name__ == "__main__":
    raise SystemExit(main())
